function cleanName(name){
 return name
  .toLowerCase()
  .replace(/[^a-z0-9]/g,"_")
  .replace(/_+/g,"_")
  .replace(/^_|_$/g,"")
}

function detectType(values){
 for(const v of values){

  if(v === null || v === "") continue

  const val = String(v).toLowerCase()

  if(val === "true" || val === "false")
   return "BOOLEAN"

  if(!isNaN(val) && Number.isInteger(Number(val)))
   return "INTEGER"

  if(!isNaN(val))
   return "NUMERIC"

  if(/^\d{4}[-/]\d{2}[-/]\d{2}/.test(val))
   return "DATE"
 }

 return "TEXT"
}

// ambil data dari node sebelumnya
let rows = $input.first().json.cleaned_rows
let columns = $('Set Text (Flow Merged)').first().json.column_names
const table = $('AI Agent Labelling').first().json.output.table_name

// normalisasi rows
if(typeof rows === "string"){
 rows = JSON.parse(rows)
}

if(!Array.isArray(rows)){
 rows = [rows]
}

// normalisasi column_names
if(typeof columns === "string"){
 columns = JSON.parse(columns)
}

// generate schema
let columnSQL = []
let indexSQL = []
for(const col of columns){
 const clean = cleanName(col)
 const values = rows.map(r => r[col])
 const type = detectType(values)
 columnSQL.push(`${clean} ${type} NULL`)
 if(type !== "TEXT"){
  indexSQL.push(
   `CREATE INDEX IF NOT EXISTS idx_${table}_${clean} ON public.${table} (${clean});`
  )
 }
}

// index penting untuk foreign key
indexSQL.push(
 `CREATE INDEX IF NOT EXISTS idx_${table}_record_manager_id ON public.${table} (record_manager_id);`
)

// CREATE TABLE
const createTableSQL = `
CREATE TABLE IF NOT EXISTS public.${table} (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
 record_manager_id BIGINT NULL,
 ${columnSQL.join(",\n")},
 created_at TIMESTAMPTZ DEFAULT now(),
 CONSTRAINT ${table}_pkey PRIMARY KEY (id),
 CONSTRAINT ${table}_record_manager_id_fkey
 FOREIGN KEY (record_manager_id)
 REFERENCES record_manager(id)
 ON DELETE CASCADE

);
`

// ENABLE RLS
const rlsSQL = `
ALTER TABLE public.${table}
ENABLE ROW LEVEL SECURITY;
`

// POLICY SELECT
const policyReadSQL = `
CREATE POLICY IF NOT EXISTS "policy_read_${table}"
ON public.${table}
FOR SELECT
USING (true);
`

// POLICY INSERT
const policyInsertSQL = `
CREATE POLICY IF NOT EXISTS "policy_insert_${table}"
ON public.${table}
FOR INSERT
WITH CHECK (true);
`

return [{
 json:{
  create_sql:createTableSQL,
  index_sql:indexSQL.join("\n"),
  rls_sql: rlsSQL,
  policy_read_sql: policyReadSQL,
  policy_insert_sql: policyInsertSQL,
  table_name:table
 }
}]
